"""
In-App Notification Models.
Complies with Master Specification Section 20.
Stores real-time system alerts, triggered trade warnings, and corporate event notices.
"""
from django.conf import settings
from django.db import models

from apps.alerts.models import AlertRule
from apps.core.models import AuditedModel


class NotificationSeverity(models.TextChoices):
    INFO = "INFO", "Information"
    SUCCESS = "SUCCESS", "Success"
    WARNING = "WARNING", "Warning"
    DANGER = "DANGER", "Danger"


class Notification(AuditedModel):
    """
    User in-app notification item generated by alert triggers or system events.
    """
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="notifications",
        db_index=True,
    )
    alert_rule = models.ForeignKey(
        AlertRule,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="notifications",
        help_text="Originating alert rule, if triggered by an alert.",
    )
    title = models.CharField(max_length=250)
    message = models.TextField()
    severity = models.CharField(
        max_length=20,
        choices=NotificationSeverity.choices,
        default=NotificationSeverity.INFO,
        db_index=True,
    )
    is_read = models.BooleanField(
        default=False,
        db_index=True,
    )
    read_at = models.DateTimeField(
        null=True,
        blank=True,
    )
    link_url = models.CharField(
        max_length=250,
        blank=True,
        help_text="Optional internal link to stock profile, portfolio, or scanner.",
    )

    class Meta:
        ordering = ["-created_at"]
        verbose_name = "Notification"
        verbose_name_plural = "Notifications"
        indexes = [
            models.Index(fields=["user", "is_read", "-created_at"], name="idx_notif_user_read"),
        ]

    def __str__(self) -> str:
        return f"{self.user.username} - [{self.severity}] {self.title}"

