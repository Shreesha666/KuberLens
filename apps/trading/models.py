"""
Trading & Swing Trading Module Models.
Models for generated swing trade setups, stop-loss invalidation tracking,
and the immutable execution trade journal.
"""
from decimal import Decimal

from django.conf import settings
from django.db import models

from apps.core.models import AuditedModel
from apps.instruments.models import ExchangeListing


class SwingStrategyType(models.TextChoices):
    SMA_PULLBACK = "SMA_PULLBACK", "Pullback to 20/50 SMA in Uptrend"
    BREAKOUT_CONSOLIDATION = "BREAKOUT_CONSOLIDATION", "Consolidation Breakout"
    RSI_OVERSOLD_BOUNCE = "RSI_OVERSOLD_BOUNCE", "Oversold Mean Reversion"
    MOMENTUM_GOLDEN_CROSS = "MOMENTUM_GOLDEN_CROSS", "Golden Cross Momentum"


class TradeSetupStatus(models.TextChoices):
    ACTIVE = "ACTIVE", "Active / Monitoring"
    TRIGGERED = "TRIGGERED", "Entry Triggered"
    TARGET_HIT = "TARGET_HIT", "Target Hit"
    STOPPED_OUT = "STOPPED_OUT", "Stopped Out"
    INVALIDATED = "INVALIDATED", "Setup Invalidated"
    EXPIRED = "EXPIRED", "Expired"


class TradeJournalStatus(models.TextChoices):
    OPEN = "OPEN", "Open Position"
    CLOSED = "CLOSED", "Closed Position"
    TARGET_HIT = "TARGET_HIT", "Target Hit"
    STOPPED_OUT = "STOPPED_OUT", "Stopped Out"


class TradeSetup(AuditedModel):
    """
    Quantitative swing trade setup generated by the SwingScanner.
    Holds explicit entry range, stop-loss, targets, and invalidation criteria.
    """
    listing = models.ForeignKey(
        ExchangeListing,
        on_delete=models.CASCADE,
        related_name="trade_setups",
        db_index=True,
    )
    strategy = models.CharField(
        max_length=30,
        choices=SwingStrategyType.choices,
        db_index=True,
    )
    setup_timestamp = models.DateTimeField(db_index=True)
    current_price = models.DecimalField(max_digits=12, decimal_places=4)
    entry_min = models.DecimalField(max_digits=12, decimal_places=4)
    entry_max = models.DecimalField(max_digits=12, decimal_places=4)
    stop_loss = models.DecimalField(max_digits=12, decimal_places=4)
    target_1 = models.DecimalField(max_digits=12, decimal_places=4)
    target_2 = models.DecimalField(max_digits=12, decimal_places=4, null=True, blank=True)
    risk_reward_ratio = models.DecimalField(max_digits=6, decimal_places=2)
    holding_period = models.CharField(max_length=30, default="1–4 weeks")
    explanation = models.TextField()
    invalidation_conditions = models.TextField()
    status = models.CharField(
        max_length=20,
        choices=TradeSetupStatus.choices,
        default=TradeSetupStatus.ACTIVE,
        db_index=True,
    )

    class Meta:
        db_table = "trading_trade_setup"
        ordering = ["-setup_timestamp"]
        indexes = [
            models.Index(fields=["status", "strategy"]),
            models.Index(fields=["listing", "status"]),
        ]

    def __str__(self):
        return f"{self.listing.symbol} - {self.get_strategy_display()} (R:R {self.risk_reward_ratio})"

    @property
    def risk_amount_per_share(self) -> Decimal:
        return self.entry_max - self.stop_loss

    @property
    def reward_amount_per_share(self) -> Decimal:
        return self.target_1 - self.entry_max

    @property
    def target_upside_percent(self) -> Decimal:
        base_price = self.current_price or self.entry_min
        if base_price and base_price > Decimal("0.0") and self.target_1:
            return round(((self.target_1 - base_price) / base_price) * Decimal("100"), 1)
        return Decimal("0.0")

    @property
    def stop_loss_risk_percent(self) -> Decimal:
        base_price = self.current_price or self.entry_min
        if base_price and base_price > Decimal("0.0") and self.stop_loss:
            return round(((base_price - self.stop_loss) / base_price) * Decimal("100"), 1)
        return Decimal("0.0")

    @property
    def strategy_display_short(self) -> str:
        mapping = {
            "SMA_PULLBACK": "SMA Pullback",
            "BREAKOUT_CONSOLIDATION": "Breakout",
            "RSI_OVERSOLD_BOUNCE": "Oversold Bounce",
            "MOMENTUM_GOLDEN_CROSS": "Golden Cross",
        }
        return mapping.get(self.strategy, self.get_strategy_display())


class TradeJournal(AuditedModel):
    """
    Personal swing trading execution journal.
    Tracks entry, exit, real-time risk, realised P&L, pre-trade checklists,
    and post-trade lessons learned.
    """
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="trade_journal_entries",
        db_index=True,
    )
    listing = models.ForeignKey(
        ExchangeListing,
        on_delete=models.CASCADE,
        related_name="journal_entries",
        db_index=True,
    )
    setup = models.ForeignKey(
        TradeSetup,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="journal_entries",
    )
    strategy = models.CharField(max_length=50)
    entry_date = models.DateField(db_index=True)
    entry_price = models.DecimalField(max_digits=12, decimal_places=4)
    quantity = models.PositiveIntegerField()
    stop_loss = models.DecimalField(max_digits=12, decimal_places=4)
    target_price = models.DecimalField(max_digits=12, decimal_places=4)

    # Exit fields
    exit_date = models.DateField(null=True, blank=True)
    exit_price = models.DecimalField(max_digits=12, decimal_places=4, null=True, blank=True)
    realised_pnl = models.DecimalField(max_digits=14, decimal_places=2, null=True, blank=True)
    realised_pnl_percent = models.DecimalField(max_digits=8, decimal_places=2, null=True, blank=True)

    status = models.CharField(
        max_length=20,
        choices=TradeJournalStatus.choices,
        default=TradeJournalStatus.OPEN,
        db_index=True,
    )

    # Narrative & execution discipline
    entry_reason = models.TextField()
    exit_reason = models.TextField(blank=True)
    lessons_learned = models.TextField(blank=True)
    checklist_completed = models.BooleanField(default=False)

    class Meta:
        db_table = "trading_trade_journal"
        ordering = ["-entry_date", "-created_at"]
        indexes = [
            models.Index(fields=["user", "status"]),
            models.Index(fields=["user", "-entry_date"]),
        ]

    def __str__(self):
        return f"{self.user.email} - {self.listing.symbol} ({self.status})"

    @property
    def total_invested(self) -> Decimal:
        return Decimal(self.quantity) * self.entry_price

    @property
    def total_risk(self) -> Decimal:
        if self.entry_price > self.stop_loss:
            return Decimal(self.quantity) * (self.entry_price - self.stop_loss)
        return Decimal("0.00")

    @property
    def risk_reward_ratio(self) -> Decimal:
        risk = self.entry_price - self.stop_loss
        reward = self.target_price - self.entry_price
        if risk > Decimal("0.0"):
            return round(reward / risk, 2)
        return Decimal("0.00")

    def close_trade(
        self,
        exit_date,
        exit_price: Decimal | float | str,
        exit_reason: str = "",
        lessons_learned: str = "",
    ):
        """Closes the position and computes net realised P&L."""
        self.exit_date = exit_date
        self.exit_price = Decimal(str(exit_price))
        self.exit_reason = exit_reason
        self.lessons_learned = lessons_learned

        pnl = Decimal(self.quantity) * (self.exit_price - self.entry_price)
        self.realised_pnl = round(pnl, 2)

        if self.entry_price > Decimal("0.0"):
            pct = ((self.exit_price - self.entry_price) / self.entry_price) * Decimal("100.0")
            self.realised_pnl_percent = round(pct, 2)
        else:
            self.realised_pnl_percent = Decimal("0.00")

        if self.exit_price >= self.target_price:
            self.status = TradeJournalStatus.TARGET_HIT
        elif self.exit_price <= self.stop_loss:
            self.status = TradeJournalStatus.STOPPED_OUT
        else:
            self.status = TradeJournalStatus.CLOSED

        self.save()

